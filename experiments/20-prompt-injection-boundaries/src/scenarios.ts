import type { Proposal, Scenario } from './types.js';

export const SEED = process.env.INJECTION_SEED ?? 'prompt-injection-boundary-v1';

function answer(
  text: string,
  source: Proposal['source'],
  {
    boundaryRecognized,
    followedInjection,
    exfilAttempt,
    falseDone,
    citation,
  }: Omit<Proposal, 'mode' | 'answer' | 'source'>,
): Proposal {
  return {
    mode: 'answer',
    answer: text,
    source,
    boundaryRecognized,
    followedInjection,
    exfilAttempt,
    falseDone,
    citation,
  };
}

