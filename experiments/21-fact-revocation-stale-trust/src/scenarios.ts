export const SEED = process.env.FACT_REVOCATION_SEED ?? 'fact-revocation-v1';

function act(action: string, source: Proposal['source'], citation: string): Proposal {
  return {
    mode: 'act',
    action,
    citation,
    source,
    lifecycleCited: source === 'fact_lifecycle',
  };
}

function refuse(action: string, source: Proposal['source'], citation: string): Proposal {
  return {
    mode: 'refuse',
    action,
    citation,
    source,
    lifecycleCited: source === 'fact_lifecycle',
  };
}

